export function generateCodePack(project: ProjectRuntimeArtifact): CodePack {
  const title = getProjectTitle(project);
  const summary = getProjectSummary(project);

  const prdText = sectionToText(project.prd);
  const architectureText = sectionToText(project.architecture);
  const tasksText = sectionToText(project.tasks);
  const exportText = sectionToText(project.exportPack);

  const allText = [
    project.input,
    prdText,
    architectureText,
    tasksText,
    exportText,
  ].join("\n");

  const extractedFeatures = extractListCandidates(`${prdText}\n${tasksText}`, 6);
  const features =
    extractedFeatures.length >= 3
      ? extractedFeatures
      : [
          "Generate a usable product runtime from one clear idea.",
          "Provide structured product, architecture, and task planning.",
          "Support secure authentication and project ownership.",
          "Prepare deployment and production readiness workflows.",
        ];

  const stack = detectTechnicalStack(allText);
  const packageName = createPackageName(title);

  const files: CodePackFile[] = [
    {
      path: "README.md",
      language: "markdown",
      description: "Project overview and setup instructions.",
      content: createReadme({
        title,
        summary,
        features,
        stack,
      }),
    },
    {
      path: "package.json",
      language: "json",
      description: "Starter dependencies and scripts.",
      content: createPackageJson(packageName),
    },
    {
      path: "app/layout.tsx",
      language: "tsx",
      description: "Next.js root layout.",
      content: createLayout(title, summary),
    },
    {
      path: "app/page.tsx",
      language: "tsx",
      description: "Generated landing page entry.",
      content: createPage(),
    },
    {
      path: "app/globals.css",
      language: "css",
      description: "Tailwind base styles.",
      content: createGlobalsCss(),
    },
    {
      path: "components/GeneratedProductHero.tsx",
      language: "tsx",
      description: "Reusable generated product hero component.",
      content: createHeroComponent(),
    },
    {
      path: "lib/project-config.ts",
      language: "ts",
      description: "Generated project configuration.",
      content: createProjectConfig({
        title,
        summary,
        features,
        stack,
      }),
    },
    {
      path: ".env.example",
      language: "env",
      description: "Safe public environment variable template.",
      content: createEnvExample(),
    },
    {
      path: "supabase/schema.sql",
      language: "sql",
      description: "Starter Supabase schema with RLS.",
      content: createSchemaSql(title),
    },
    {
      path: "tests/smoke-test.md",
      language: "markdown",
      description: "Manual smoke test checklist.",
      content: createSmokeTest(title),
    },
  ];

  return {
    projectId: project.projectId,
    title,
    summary,
    fileCount: files.length,
    generatedAt: new Date().toISOString(),
    files,
    nextSteps: [
      "Review generated files before production use.",
      "Create the generated file tree in a new repository or export workflow.",
      "Add real API routes, database migrations, and authentication flows.",
      "Run npm install and npm run build in the generated project.",
      "Perform security review before deployment.",
    ],
  };
}