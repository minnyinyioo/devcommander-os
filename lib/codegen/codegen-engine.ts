type UnknownRecord = Record<string, unknown>;

function isRecord(value: unknown): value is UnknownRecord {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function sectionToText(section: RuntimeSection): string {
  if (section === null || section === undefined) return "";

  if (typeof section === "string") return section;

  if (Array.isArray(section)) {
    return section
      .map((item) => {
        if (typeof item === "string") return item;

        try {
          return JSON.stringify(item, null, 2);
        } catch {
          return "";
        }
      })
      .join("\n");
  }

  try {
    return JSON.stringify(section, null, 2);
  } catch {
    return "";
  }
}

function readString(record: UnknownRecord | undefined, key: string): string | null {
  if (!record) return null;

  const value = record[key];

  return typeof value === "string" && value.trim() ? value.trim() : null;
}

function cleanLine(value: string): string {
  return value
    .replace(/^[-*•\d.)\s]+/, "")
    .replace(/\*\*/g, "")
    .trim();
}

function extractListCandidates(text: string, limit: number): string[] {
  const candidates = text
    .split("\n")
    .map(cleanLine)
    .filter((line) => line.length >= 10 && line.length <= 120)
    .filter((line) => !line.includes("{") && !line.includes("}"))
    .filter((line) => !line.toLowerCase().startsWith("import "))
    .filter((line) => !line.toLowerCase().startsWith("export "));

  return Array.from(new Set(candidates)).slice(0, limit);
}

function getProjectTitle(project: ProjectRuntimeArtifact): string {
  if (isRecord(project.prd)) {
    const productName =
      readString(project.prd, "productName") ??
      readString(project.prd, "title") ??
      readString(project.prd, "name");

    if (productName) return productName;
  }

  const firstSentence = project.input.split(/[.!?。！？]/)[0]?.trim();

  return firstSentence && firstSentence.length >= 3
    ? firstSentence.slice(0, 80)
    : "Generated Product";
}

function getProjectSummary(project: ProjectRuntimeArtifact): string {
  if (isRecord(project.prd)) {
    const summary =
      readString(project.prd, "summary") ??
      readString(project.prd, "overview") ??
      readString(project.prd, "description");

    if (summary) return summary;
  }

  return project.input.trim() || "Generated by DevCommander OS.";
}

function createPackageName(title: string): string {
  const slug = title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48);

  return slug || "generated-product";
}

function detectTechnicalStack(text: string): string[] {
  const lower = text.toLowerCase();
  const stack: string[] = [];

  if (lower.includes("next")) stack.push("Next.js");
  if (lower.includes("typescript")) stack.push("TypeScript");
  if (lower.includes("tailwind")) stack.push("Tailwind CSS");
  if (lower.includes("supabase")) stack.push("Supabase");
  if (lower.includes("postgres")) stack.push("Postgres");
  if (lower.includes("auth")) stack.push("Authentication");
  if (lower.includes("vercel")) stack.push("Vercel");

  if (stack.length === 0) {
    return ["Next.js", "TypeScript", "Tailwind CSS", "Supabase", "Vercel"];
  }

  return Array.from(new Set(stack)).slice(0, 8);
}

