function buildNextActions(mode: AiRouterMode): string[] {
  if (mode === "local_first") {
    return [
      "Keep Local Runtime Engine as the default provider.",
      "Add server-only provider key support later through API routes.",
      "Do not expose AI provider keys in browser code.",
      "Use AI Router rules to decide which engine handles PRD, architecture, code, deploy, and monitoring tasks.",
    ];
  }

  if (mode === "cloud_ready") {
    return [
      "Create server-side API route for provider execution.",
      "Add provider key validation without exposing secrets.",
      "Keep local fallback enabled for every task type.",
      "Add audit events for ai.route.selected and ai.route.failed.",
    ];
  }

  return [
    "Add role-based access control before enabling team AI routing.",
    "Create server-side provider execution logs.",
    "Add per-workspace provider policy configuration.",
    "Add cost and rate-limit tracking before production AI routing.",
  ];
}

export function generateAiRouterPlan(
  project: ProjectRuntimeArtifact,
): AiRouterPlan {
  const mode = resolveRouterMode(project);

  return {
    projectId: project.projectId,
    title: getProjectTitle(project),
    summary: getProjectSummary(project),
    mode,
    providers: buildProviders(),
    rules: buildRoutingRules(mode),
    safetyPolicies: buildSafetyPolicies(),
    nextActions: buildNextActions(mode),
    generatedAt: new Date().toISOString(),
  };
}