function buildRule({
  taskType,
  label,
  primaryProvider,
  fallbackProviders,
  reason,
}: {
  taskType: AiTaskType;
  label: string;
  primaryProvider: AiProviderId;
  fallbackProviders: AiProviderId[];
  reason: string;
}): AiRoutingRule {
  return {
    taskType,
    label,
    primaryProvider,
    fallbackProviders,
    reason,
  };
}

function buildRoutingRules(mode: AiRouterMode): AiRoutingRule[] {
  const cloudPrimary: AiProviderId =
    mode === "local_first" ? "local" : "openai";

  return [
    buildRule({
      taskType: "product",
      label: "Product / PRD generation",
      primaryProvider: cloudPrimary,
      fallbackProviders: ["local", "anthropic", "gemini"],
      reason:
        "Product planning needs strong reasoning but must fall back to local deterministic generation when no provider key exists.",
    }),
    buildRule({
      taskType: "architecture",
      label: "Architecture generation",
      primaryProvider: cloudPrimary,
      fallbackProviders: ["local", "anthropic", "gemini"],
      reason:
        "Architecture generation requires system design reasoning, security boundaries, and stack consistency checks.",
    }),
    buildRule({
      taskType: "code",
      label: "Code Pack generation",
      primaryProvider: "local",
      fallbackProviders: ["openai", "anthropic", "gemini"],
      reason:
        "Current Code Pack output is deterministic and secret-safe. Cloud AI can be added later for richer code generation.",
    }),
    buildRule({
      taskType: "deployment",
      label: "Deployment Pack generation",
      primaryProvider: "local",
      fallbackProviders: ["openai", "anthropic"],
      reason:
        "Deployment packs should be deterministic, auditable, and stable before adding external AI suggestions.",
    }),
    buildRule({
      taskType: "monitoring",
      label: "Monitoring and audit review",
      primaryProvider: "local",
      fallbackProviders: ["anthropic", "openai"],
      reason:
        "Audit and readiness checks must remain stable even when cloud AI providers are unavailable.",
    }),
  ];
}

