function buildRollbackPlan(): string[] {
  return [
    "Keep the latest stable Git tag before production deployment.",
    "If deployment fails, rollback to the previous successful Vercel deployment.",
    "If database migration fails, stop deployment and restore from the last known stable schema.",
    "Never roll forward with broken RLS, missing environment variables, or failed build output.",
    "Document the failed deployment reason in Activity / Audit logs.",
  ];
}

function buildNextActions(riskLevel: DeployRiskLevel): string[] {
  if (riskLevel === "low") {
    return [
      "Run npm run build one final time.",
      "Confirm Vercel environment variables.",
      "Deploy to staging or preview environment.",
      "Run smoke tests on /dashboard, /workspace, /activity, /project/[id], /code, and /readiness.",
    ];
  }

  if (riskLevel === "medium") {
    return [
      "Review authentication and RLS policies before production.",
      "Confirm all required environment variables exist in Vercel.",
      "Run smoke tests on all runtime pages.",
      "Prepare rollback tag before deploying.",
    ];
  }

  return [
    "Do not deploy to production yet.",
    "Improve security, database ownership, monitoring, and rollback plans.",
    "Run the Production Readiness Gate again.",
    "Only deploy after build, auth, RLS, and environment checks pass.",
  ];
}

export function generateDeploymentPack(
  project: ProjectRuntimeArtifact,
): DeploymentPack {
  const riskLevel = resolveRiskLevel(project);

  return {
    projectId: project.projectId,
    title: getProjectTitle(project),
    summary: getProjectSummary(project),
    platform: "vercel",
    riskLevel,
    riskSummary: getRiskSummary(riskLevel),
    environmentVariables: buildEnvironmentVariables(),
    commands: buildCommands(),
    checklist: buildChecklist(riskLevel),
    rollbackPlan: buildRollbackPlan(),
    nextActions: buildNextActions(riskLevel),
    generatedAt: new Date().toISOString(),
  };
}