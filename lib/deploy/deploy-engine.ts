type UnknownRecord = Record<string, unknown>;

function isRecord(value: unknown): value is UnknownRecord {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function readString(record: UnknownRecord | undefined, key: string): string | null {
  if (!record) return null;

  const value = record[key];

  return typeof value === "string" && value.trim() ? value.trim() : null;
}

function sectionToText(section: RuntimeSection): string {
  if (section === null || section === undefined) return "";

  if (typeof section === "string") return section;

  if (Array.isArray(section)) {
    return section
      .map((item) => {
        if (typeof item === "string") return item;

        try {
          return JSON.stringify(item, null, 2);
        } catch {
          return "";
        }
      })
      .join("\n");
  }

  try {
    return JSON.stringify(section, null, 2);
  } catch {
    return "";
  }
}

function getProjectTitle(project: ProjectRuntimeArtifact): string {
  if (isRecord(project.prd)) {
    const productName =
      readString(project.prd, "productName") ??
      readString(project.prd, "title") ??
      readString(project.prd, "name");

    if (productName) return productName;
  }

  const firstSentence = project.input.split(/[.!?。！？]/)[0]?.trim();

  return firstSentence && firstSentence.length >= 3
    ? firstSentence.slice(0, 80)
    : "Generated Product";
}

function getProjectSummary(project: ProjectRuntimeArtifact): string {
  if (isRecord(project.prd)) {
    const summary =
      readString(project.prd, "summary") ??
      readString(project.prd, "overview") ??
      readString(project.prd, "description");

    if (summary) return summary;
  }

  return project.input.trim() || "Generated by DevCommander OS.";
}

function hasAny(text: string, keywords: string[]): boolean {
  const lower = text.toLowerCase();

  return keywords.some((keyword) => lower.includes(keyword.toLowerCase()));
}

function resolveRiskLevel(project: ProjectRuntimeArtifact): DeployRiskLevel {
  const architectureText = sectionToText(project.architecture);
  const tasksText = sectionToText(project.tasks);
  const exportText = sectionToText(project.exportPack);

  const allText = [
    project.input,
    architectureText,
    tasksText,
    exportText,
  ].join("\n");

  const hasSecurity = hasAny(allText, [
    "auth",
    "authentication",
    "authorization",
    "rls",
    "permission",
    "role",
    "access control",
  ]);

  const hasDeployment = hasAny(allText, [
    "deploy",
    "deployment",
    "vercel",
    "production",
    "rollback",
    "environment",
  ]);

  const hasMonitoring = hasAny(allText, [
    "monitor",
    "logging",
    "audit",
    "alert",
    "health",
  ]);

  if (hasSecurity && hasDeployment && hasMonitoring) return "low";
  if (hasSecurity || hasDeployment) return "medium";
  return "high";
}

function getRiskSummary(riskLevel: DeployRiskLevel): string {
  if (riskLevel === "low") {
    return "The project has clear deployment, security, and monitoring signals. It is suitable for controlled staging deployment after final manual review.";
  }

  if (riskLevel === "medium") {
    return "The project has partial deployment readiness. Review environment variables, authentication, database ownership, and rollback before production.";
  }

  return "The project should not be deployed to production yet. Security, environment handling, monitoring, and rollback planning need stronger coverage.";
}

