import type {
  AiCodeGenerationProvider,
  AiCodeGenerationRequest,
  AiCodeGenerationResponse,
  AiGeneratedCodeFile,
} from "./codegen-api-types";

type OpenAiMessage = {
  role: "system" | "user";
  content: string;
};

type OpenAiChoice = {
  message?: {
    content?: string;
  };
};

type OpenAiResponse = {
  choices?: OpenAiChoice[];
};

type ParsedProviderOutput = {
  summary: string;
  runInstructions: string[];
  files: AiGeneratedCodeFile[];
};

const MAX_PROMPT_LENGTH = 4000;
const DEFAULT_MAX_FILES = 8;

function cleanText(value: string, maxLength = MAX_PROMPT_LENGTH): string {
  return value.replace(/\u0000/g, "").trim().slice(0, maxLength);
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function asString(value: unknown): string {
  return typeof value === "string" ? value : "";
}

function isSafeRelativePath(path: string): boolean {
  if (!path || path.startsWith("/") || path.includes("..") || path.includes("\\")) {
    return false;
  }

  return /^[a-zA-Z0-9._/@-]+$/.test(path);
}

function normalizeFile(value: unknown): AiGeneratedCodeFile | null {
  if (!isRecord(value)) {
    return null;
  }

  const path = asString(value.path);
  const language = asString(value.language) || "text";
  const purpose = asString(value.purpose) || "Generated project file";
  const content = asString(value.content);

  if (!isSafeRelativePath(path) || content.length === 0) {
    return null;
  }

  return {
    path,
    language,
    purpose,
    riskLevel: "review",
    content,
  };
}

