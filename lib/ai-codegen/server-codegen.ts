function extractJson(text: string): string {
  const trimmed = text.trim();

  if (trimmed.startsWith("```")) {
    return trimmed
      .replace(/^```json/i, "")
      .replace(/^```/i, "")
      .replace(/```$/i, "")
      .trim();
  }

  return trimmed;
}

function parseProviderOutput(rawText: string, maxFiles: number): ParsedProviderOutput | null {
  try {
    const parsed = JSON.parse(extractJson(rawText)) as unknown;

    if (!isRecord(parsed)) {
      return null;
    }

    const rawFiles = Array.isArray(parsed.files) ? parsed.files : [];
    const files = rawFiles
      .map(normalizeFile)
      .filter((file): file is AiGeneratedCodeFile => file !== null)
      .slice(0, maxFiles);

    if (files.length === 0) {
      return null;
    }

    const rawInstructions = Array.isArray(parsed.runInstructions)
      ? parsed.runInstructions
      : [];

    return {
      summary: asString(parsed.summary) || "Generated code package from AI provider.",
      runInstructions: rawInstructions
        .map(asString)
        .filter((item) => item.length > 0)
        .slice(0, 8),
      files,
    };
  } catch {
    return null;
  }
}

async function generateWithOpenAi(
  prompt: string,
  maxFiles: number,
): Promise<ParsedProviderOutput | null> {
  const apiKey = process.env.OPENAI_API_KEY?.trim();

  if (!apiKey) {
    return null;
  }

  const model = process.env.OPENAI_MODEL?.trim() || "gpt-4o-mini";

  const messages: OpenAiMessage[] = [
    {
      role: "system",
      content:
        "You generate safe starter code packages. Return JSON only. Do not include secrets. Use relative file paths only. Do not use absolute paths. Do not include API keys.",
    },
    {
      role: "user",
      content: `Generate a Next.js TypeScript starter code package for this request:

${cleanText(prompt)}

Return exactly this JSON shape:
{
  "summary": "short summary",
  "runInstructions": ["npm install", "npm run dev", "npm run build"],
  "files": [
    {
      "path": "relative/path",
      "language": "tsx",
      "purpose": "why this file exists",
      "content": "file content"
    }
  ]
}

Limit to ${maxFiles} files.`,
    },
  ];

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 30000);

  try {
    const response = await fetch("https://api.openai.com/v1/chat/completions", {
      method: "POST",
      signal: controller.signal,
      headers: {
        Authorization: `Bearer ${apiKey}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model,
        temperature: 0.2,
        response_format: { type: "json_object" },
        messages,
      }),
    });

    if (!response.ok) {
      return null;
    }

    const data = (await response.json()) as OpenAiResponse;
    const content = data.choices?.[0]?.message?.content;

    if (!content) {
      return null;
    }

    return parseProviderOutput(content, maxFiles);
  } catch {
    return null;
  } finally {
    clearTimeout(timeout);
  }
}

export async function generateCodeFromRequest(
  request: AiCodeGenerationRequest,
): Promise<AiCodeGenerationResponse> {
  const prompt = cleanText(request.prompt);
  const requestedProvider = request.provider || "local";
  const maxFiles = Math.max(
    1,
    Math.min(request.maxFiles || DEFAULT_MAX_FILES, 12),
  );

  if (prompt.length < 8) {
    throw new Error("Prompt is too short. Describe the product or problem first.");
  }

  let provider: AiCodeGenerationProvider = "local";
  let fallbackUsed = false;
  let generated: ParsedProviderOutput | null = null;

  if (requestedProvider === "openai") {
    generated = await generateWithOpenAi(prompt, maxFiles);

    if (generated) {
      provider = "openai";
    } else {
      fallbackUsed = true;
      generated = generateLocalFallback(prompt);
    }
  } else {
    generated = generateLocalFallback(prompt);
  }

  return {
    generatedAt: new Date().toISOString(),
    provider,
    fallbackUsed,
    summary: generated.summary,
    runInstructions: generated.runInstructions,
    files: generated.files.slice(0, maxFiles),
    safety: {
      secretsReturned: false,
      requiresHumanReview: true,
      warnings: [
        "Generated code must be reviewed before deployment.",
        "Do not commit real API keys.",
        "Run npm install and npm run build before launch.",
      ],
    },
  };
}
