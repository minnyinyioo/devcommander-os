type UnknownRecord = Record<string, unknown>;

function isRecord(value: unknown): value is UnknownRecord {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function readString(record: UnknownRecord | undefined, key: string): string | null {
  if (!record) return null;

  const value = record[key];

  return typeof value === "string" && value.trim() ? value.trim() : null;
}

function sectionToText(section: RuntimeSection): string {
  if (section === null || section === undefined) return "";

  if (typeof section === "string") return section;

  if (Array.isArray(section)) {
    return section
      .map((item) => {
        if (typeof item === "string") return item;

        try {
          return JSON.stringify(item, null, 2);
        } catch {
          return "";
        }
      })
      .join("\n");
  }

  try {
    return JSON.stringify(section, null, 2);
  } catch {
    return "";
  }
}

function getProjectTitle(project: ProjectRuntimeArtifact): string {
  if (isRecord(project.prd)) {
    const productName =
      readString(project.prd, "productName") ??
      readString(project.prd, "title") ??
      readString(project.prd, "name");

    if (productName) return productName;
  }

  const firstSentence = project.input.split(/[.!?。！？]/)[0]?.trim();

  return firstSentence && firstSentence.length >= 3
    ? firstSentence.slice(0, 80)
    : "Generated Product";
}

function getProjectSummary(project: ProjectRuntimeArtifact): string {
  if (isRecord(project.prd)) {
    const summary =
      readString(project.prd, "summary") ??
      readString(project.prd, "overview") ??
      readString(project.prd, "description");

    if (summary) return summary;
  }

  return project.input.trim() || "Generated by DevCommander OS.";
}

function getAssetStatus(score: number): HandoverAsset["status"] {
  if (score >= 75) return "ready";
  if (score >= 55) return "needs_review";
  return "missing";
}

function resolveHandoverStatus({
  readinessScore,
  monitorScore,
  deployRisk,
}: {
  readinessScore: number;
  monitorScore: number;
  deployRisk: "low" | "medium" | "high";
}): ProjectHandoverPack["handoverStatus"] {
  if (readinessScore >= 75 && monitorScore >= 75 && deployRisk !== "high") {
    return "ready_for_internal_handoff";
  }

  if (readinessScore >= 55 && monitorScore >= 55) {
    return "needs_review";
  }

  return "not_ready";
}

function buildAssets(project: ProjectRuntimeArtifact): HandoverAsset[] {
  const readinessReport = generateReadinessReport(project);
  const codePack = generateCodePack(project);
  const deploymentPack = generateDeploymentPack(project);
  const testPack = generateTestPack(project);
  const monitorReport = generateProjectMonitorReport(project);
  const opsRunbook = generateOpsRunbook(project);
  const routerPlan = generateAiRouterPlan(project);

  const projectText = [
    project.input,
    sectionToText(project.prd),
    sectionToText(project.architecture),
    sectionToText(project.tasks),
    sectionToText(project.exportPack),
  ].join("\n");

  const hasProjectRuntime = projectText.trim().length > 0;
  const testScore =
    testPack.readinessSignal === "safe_to_test"
      ? 86
      : testPack.readinessSignal === "needs_review"
        ? 66
        : 42;

  const deployScore =
    deploymentPack.riskLevel === "low"
      ? 86
      : deploymentPack.riskLevel === "medium"
        ? 66
        : 42;

  const opsScore =
    opsRunbook.operatingStage === "post_launch"
      ? 86
      : opsRunbook.operatingStage === "launch_ready"
        ? 72
        : 52;

  const routerScore =
    routerPlan.mode === "enterprise"
      ? 86
      : routerPlan.mode === "cloud_ready"
        ? 76
        : 68;

  return [
    {
      id: "project-runtime",
      name: "Project Runtime",
      type: "runtime",
      status: hasProjectRuntime ? "ready" : "missing",
      description:
        "Project Brain, PRD, Architecture, Tasks, and Export Pack are available in the main runtime.",
    },
    {
      id: "ai-router",
      name: "AI Router",
      type: "ai",
      status: getAssetStatus(routerScore),
      description:
        "Local-first AI routing rules and task runner are available for product, architecture, code, deploy, and monitor tasks.",
    },
    {
      id: "code-pack",
      name: "Code Pack",
      type: "code",
      status: codePack.fileCount >= 5 ? "ready" : "needs_review",
      description: `${codePack.fileCount} generated files are available for review and ZIP export.`,
    },
    {
      id: "tests",
      name: "Test Pack",
      type: "test",
      status: getAssetStatus(testScore),
      description:
        "Smoke, route, security, data, deployment, and acceptance checks are available.",
    },
    {
      id: "readiness",
      name: "Readiness Gate",
      type: "readiness",
      status: getAssetStatus(readinessReport.overallScore),
      description: `Readiness score is ${readinessReport.overallScore}/100.`,
    },
    {
      id: "deploy",
      name: "Deployment Pack",
      type: "deploy",
      status: getAssetStatus(deployScore),
      description: `Deployment risk is ${deploymentPack.riskLevel}.`,
    },
    {
      id: "monitor",
      name: "Project Monitor",
      type: "monitor",
      status: getAssetStatus(monitorReport.overallHealthScore),
      description: `Runtime health score is ${monitorReport.overallHealthScore}/100.`,
    },
    {
      id: "ops",
      name: "Operations Runbook",
      type: "ops",
      status: getAssetStatus(opsScore),
      description: `Operating stage is ${opsRunbook.operatingStage}.`,
    },
  ];
}

