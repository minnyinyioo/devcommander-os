function buildRisks(
  handoverStatus: ProjectHandoverPack["handoverStatus"],
): string[] {
  if (handoverStatus === "ready_for_internal_handoff") {
    return [
      "This project is suitable for internal handoff, but production launch still requires final build, test, deploy, and smoke checks.",
      "External AI providers should not be enabled until server-side secret handling is added.",
    ];
  }

  if (handoverStatus === "needs_review") {
    return [
      "Some generated assets need review before handoff.",
      "The next owner should inspect Tests, Readiness, Deploy, Monitor, and Ops before implementation.",
      "Production deployment should wait until critical checks are cleared.",
    ];
  }

  return [
    "This project is not ready for handoff.",
    "Core planning, testing, readiness, monitoring, or deployment review is incomplete.",
    "Do not transfer ownership until missing or critical assets are resolved.",
  ];
}

function buildNextOwnerActions(
  handoverStatus: ProjectHandoverPack["handoverStatus"],
): string[] {
  if (handoverStatus === "ready_for_internal_handoff") {
    return [
      "Copy the handover pack Markdown.",
      "Give the next owner the repository, latest tag, deployment notes, and project ID.",
      "Ask the next owner to run npm run build before making changes.",
      "Use Ops Runbook for incidents and release control.",
    ];
  }

  if (handoverStatus === "needs_review") {
    return [
      "Review assets marked needs_review.",
      "Run Tests and Readiness again.",
      "Resolve monitor warnings before handoff.",
      "Update Ops Runbook if deployment or security assumptions changed.",
    ];
  }

  return [
    "Strengthen product, architecture, tasks, tests, readiness, deploy, monitor, and ops first.",
    "Do not hand over this project as production-ready.",
    "Generate a new handover pack after critical gaps are resolved.",
  ];
}

export function generateProjectHandoverPack(
  project: ProjectRuntimeArtifact,
): ProjectHandoverPack {
  const readinessReport = generateReadinessReport(project);
  const monitorReport = generateProjectMonitorReport(project);
  const deploymentPack = generateDeploymentPack(project);

  const handoverStatus = resolveHandoverStatus({
    readinessScore: readinessReport.overallScore,
    monitorScore: monitorReport.overallHealthScore,
    deployRisk: deploymentPack.riskLevel,
  });

  return {
    projectId: project.projectId,
    title: getProjectTitle(project),
    summary: getProjectSummary(project),
    handoverStatus,
    assets: buildAssets(project),
    sections: buildSections(project),
    risks: buildRisks(handoverStatus),
    nextOwnerActions: buildNextOwnerActions(handoverStatus),
    generatedAt: new Date().toISOString(),
  };
}
